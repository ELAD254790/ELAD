def _streak_label(days: int) -> str:
    if days == 0:
        return "יום 1"
    elif days < 3:
        return "ימים ראשונים — הכי קשה"
    elif days < 7:
        return "שבוע ראשון"
    elif days < 14:
        return "שבועיים — הגוף מתאפס"
    elif days < 30:
        return f"{days} ימים — שינוי עמוק"
    elif days < 90:
        return f"{days} ימים — חזרת לשליטה"
    else:
        return f"{days} ימים — ניצחון אמיתי"
